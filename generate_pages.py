def generate_site():
    template_file = "template.html"
    if not os.path.exists(template_file):
        print(f"[오류] '{template_file}' 파일이 없습니다. template.html을 먼저 만들어 주세요.")
        return

    with open(template_file, "r", encoding="utf-8") as f:
        template_html = f.read()

    def write_html(folder_path, region_name, title, desc, hero_desc, voice_desc):
        os.makedirs(folder_path, exist_ok=True)
        file_path = os.path.join(folder_path, "index.html")
        
        content = template_html.replace("{{REGION_NAME}}", region_name)
        content = content.replace("{{PAGE_TITLE}}", title)
        content = content.replace("{{PAGE_DESC}}", desc)
        content = content.replace("{{HERO_DESC}}", hero_desc)
        content = content.replace("{{VOICE_DESC}}", voice_desc)
        
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(content)

    total_count = 0
    print(f">> 퀸즈홈테라피 풍성한 콘텐츠 엔진 가동 (타이틀 {len(ALL_TITLE_TEMPLATES)}개 / 디스크립션 {len(ALL_DESC_TEMPLATES)}개 풀)")

    for sido_key, sido_val in regions_data.items():
        sido_name = sido_val["name"]
        
        # 1. 시/도 단위
        s_title = f"{sido_name}출장마사지 | 24시 홈타이 퀸즈홈테라피"
        s_desc = f"{sido_name} 전지역 출장마사지 퀸즈홈테라피. 자택·호텔·오피스텔 빠른 방문, 선입금 없는 100% 후불제 맞춤 힐링 케어."
        s_hero = f"{sido_name} 전지역 위치와 시간을 먼저 듣고 오늘 필요한 맞춤 힐링 코스를 차분히 맞춥니다."
        s_voice = f"{sido_name}에서 밖으로 다시 나갈 힘보다 조용한 방문이 먼저인 밤. 위치와 희망 시간을 듣고 가능한 일정과 코스를 차분하게 정리합니다."
        write_html(sido_key, sido_name, s_title, s_desc, s_hero, s_voice)
        total_count += 1
        
        for dist_key, dist_val in sido_val["districts"].items():
            dist_name = dist_val["name"]
            full_dist_name = f"{sido_name} {dist_name}"
            dist_path = os.path.join(sido_key, dist_key)
            
            # 2. 구/시 단위
            d_title = f"{dist_name}출장마사지 | {full_dist_name} 홈타이 예약 퀸즈"
            d_desc = f"{full_dist_name} 출장마사지 안내. {dist_name} 전지역 30분 내 빠른 방문, 타이·아로마·스페셜 힐링 테라피."
            d_hero = f"{full_dist_name} 위치와 시간을 먼저 듣고 오늘 필요한 맞춤 힐링 코스를 차분히 맞춥니다."
            d_voice = f"{full_dist_name} 일대에서 밖으로 나갈 필요 없이 계신 곳에서 편안하게 받는 프라이빗 테라피 서비스."
            write_html(dist_path, full_dist_name, d_title, d_desc, d_hero, d_voice)
            total_count += 1
            
            # 3. 세부 동 단위 (100개 이상의 조합에서 고유 매핑)
            for dong in dist_val["dongs"]:
                dong_path = os.path.join(dist_path, dong)
                full_dong_name = f"{dist_name} {dong}"
                
                t_idx = get_unique_index(full_dong_name + "_t", len(ALL_TITLE_TEMPLATES))
                d_idx = get_unique_index(full_dong_name + "_d", len(ALL_DESC_TEMPLATES))
                h_idx = get_unique_index(full_dong_name + "_h", len(hero_desc_list))
                v_idx = get_unique_index(full_dong_name + "_v", len(voice_desc_list))
                
                dong_title = ALL_TITLE_TEMPLATES[t_idx].format(dong=dong, dist=dist_name)
                dong_desc = ALL_DESC_TEMPLATES[d_idx].format(dong=dong, dist=dist_name)
                dong_hero = hero_desc_list[h_idx].format(dong=dong, dist=dist_name)
                dong_voice = voice_desc_list[v_idx].format(dong=dong, dist=dist_name)
                
                write_html(dong_path, full_dong_name, dong_title, dong_desc, dong_hero, dong_voice)
                total_count += 1

    print(f">> 완료! 총 {total_count}개의 고유하고 풍성한 지역 페이지가 생성되었습니다.")

if __name__ == "__main__":
    generate_site()